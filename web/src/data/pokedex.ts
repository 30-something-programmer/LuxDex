// Deduplicate ALOLA_DEX_RAW - keep first occurrence of each key
const seenKeys = new Set<string>();
const seenAlolaNums = new Set<number>();
const ALOLA_DEX = ALOLA_DEX_RAW.filter(([alolaNum, , key]) => {
  if (seenAlolaNums.has(alolaNum) || seenKeys.has(key)) return false;
  seenAlolaNums.add(alolaNum);
  seenKeys.add(key);
  return true;
});

// Generation lookup by national dex number
function generation(n: number): number {
  if (n <= 151) return 1;
  if (n <= 251) return 2;
  if (n <= 386) return 3;
  if (n <= 493) return 4;
  if (n <= 649) return 5;
  if (n <= 721) return 6;
  return 7;
}

// Build Alola dex entries
export const ALOLA_ENTRIES: PokedexEntry[] = ALOLA_DEX.map(([alola, national, key, name]) => ({
  key,
  name,
  nationalDex: national,
  alolaDex: alola,
  generation: generation(national),
}));

